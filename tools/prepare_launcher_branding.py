#!/usr/bin/env python3
"""Resize supplied app art and bake a small transparent native launcher logo."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def prepare():
 folder=ROOT/'assets/branding'
 with Image.open(folder/'ProsperoCraft2.png') as source:
  source.convert('RGBA').resize((512,512),Image.Resampling.LANCZOS).save(folder/'icon0.png')
 with Image.open(folder/'ProsperoCraftTransparent.png') as source:
  logo=source.convert('RGBA').resize((72,72),Image.Resampling.LANCZOS)
 pixels=list(logo.getdata())
 # Alpha is composited against the launcher's constant sidebar color. Fully
 # transparent pixels remain skipped; no texture decoder or runtime dependency.
 values=[]
 for red,green,blue,alpha in pixels:
  if not alpha:values.append(0);continue
  rgb=[(v*alpha+b*(255-alpha)+127)//255 for v,b in zip((red,green,blue),(16,34,28))]
  values.append(0xff000000|(rgb[2]<<16)|(rgb[1]<<8)|rgb[0])
 header='// Generated by tools/prepare_launcher_branding.py from supplied transparent PNG.\n#pragma once\n#include <cstdint>\nnamespace prospero_menu {\ninline constexpr std::uint32_t logo_pixels[72*72]={\n'
 header+='\n'.join(','.join(f'0x{x:08x}u' for x in values[i:i+12])+',' for i in range(0,len(values),12))+'\n};\n}\n'
 (ROOT/'client/launcher/branding_logo.hpp').write_text(header)
 p=folder/'branding.json';record=json.loads(p.read_text());digest=lambda name:hashlib.sha256((folder/name).read_bytes()).hexdigest()
 record.update(source='ProsperoCraft2.png',source_sha256=digest('ProsperoCraft2.png'),icon_sha256=digest('icon0.png'),processing='User-supplied ProsperoCraft2.png resized to512x512RGBA with Lanczos; artwork unchanged',scope='Development076 and future packaging; preserved075/074 and earlier releases unchanged',launcher_source='ProsperoCraftTransparent.png',launcher_source_sha256=digest('ProsperoCraftTransparent.png'),launcher_processing='72x72RGBA Lanczos; alpha composited onto native sidebar color, transparent pixels skipped')
 p.write_text(json.dumps(record,indent=2)+'\n')
if __name__=='__main__':prepare()
